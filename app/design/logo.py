"""Generates app/design/logo.svg, the Nordyg logo, from its geometry.

The mark is an N drawn as one liquid shape: two big circles (top left,
bottom right) joined by a diagonal neck that narrows to a waist, and two
legs, each a thin stroke ending in a smaller circle. The right leg is the
left one turned half a turn around the centre, so the shape is the same
upside down. The parts melt into each other with a smooth minimum, and the
outline is the zero line of that distance field.

To tweak the logo, change PARAMS and run (needs numpy and contourpy):

    python3 app/design/logo.py
    make icon

Coordinates are in the 1254 px space of the original artwork the shape was
fitted to; the output is centred and scaled into a 1024 canvas.
"""
from pathlib import Path

import contourpy
import numpy as np

PARAMS = {
    "c1": (459.6, 433.0, 122.3),   # top-left circle: x, y, radius
    "c2": (830.5, 767.4, 120.8),   # bottom-right circle
    "waist": 22.0,                 # neck radius at its narrowest, halfway
    "flare": 70.0,                 # how much the neck widens towards each circle
    "leg": ((394.6, 428.1), (474.6, 770.9), 22.3),  # left leg: from, to, radius
    "foot": 80.2,                  # radius of the circle the left leg ends in
    "melt": 73.7,                  # smooth-minimum radius: how softly parts join
    "size": 0.64,                  # the shape's larger side, as a share of the canvas
}
GRADIENT = ("#3fe3ff", "#2f5bff")  # top left to bottom right

GRID = 1254


def outline(p):
    yy, xx = np.mgrid[:GRID, :GRID].astype(float)

    def circle(x, y, r):
        return np.hypot(xx - x, yy - y) - r

    def capsule(a, b, r):
        bax, bay = b[0] - a[0], b[1] - a[1]
        h = np.clip(((xx - a[0]) * bax + (yy - a[1]) * bay) / (bax * bax + bay * bay), 0, 1)
        return np.hypot(xx - a[0] - bax * h, yy - a[1] - bay * h) - r

    def smin(a, b):
        k = p["melt"]
        h = np.clip(0.5 + 0.5 * (b - a) / k, 0, 1)
        return b * (1 - h) + a * h - k * h * (1 - h)

    (x1, y1, r1), (x2, y2, r2) = p["c1"], p["c2"]
    d = smin(circle(x1, y1, r1), circle(x2, y2, r2))

    # The neck: circles along the diagonal, narrowest halfway.
    neck = None
    for t in np.linspace(0, 1, 60):
        r = p["waist"] + p["flare"] * (2 * t - 1) ** 2
        c = circle(x1 + (x2 - x1) * t, y1 + (y2 - y1) * t, r)
        neck = c if neck is None else np.minimum(neck, c)
    d = smin(d, neck)

    # The legs: the left one, and its half-turn copy on the right.
    (a, b, r) = p["leg"]
    mx, my = (x1 + x2) / 2, (y1 + y2) / 2
    for flip in (False, True):
        fa = (2 * mx - a[0], 2 * my - a[1]) if flip else a
        fb = (2 * mx - b[0], 2 * my - b[1]) if flip else b
        d = smin(d, capsule(fa, fb, r))
        d = smin(d, circle(fb[0], fb[1], p["foot"]))

    pts = max(contourpy.contour_generator(z=d).lines(0.0), key=len)
    lo, hi = pts.min(0), pts.max(0)
    return (pts - (lo + hi) / 2) * (1024 * p["size"] / max(hi - lo)) + 512


def simplify(p, tol=0.25):
    """Douglas-Peucker on a closed polyline, split at the farthest point."""
    def rec(a, b):
        if b <= a + 1:
            return [a]
        seg = p[b] - p[a]
        v = p[a + 1:b] - p[a]
        dist = np.abs(seg[0] * v[:, 1] - seg[1] * v[:, 0]) / (np.hypot(*seg) or 1)
        i = int(np.argmax(dist)) + a + 1
        return rec(a, i) + rec(i, b) if dist.max() > tol else [a]
    k = int(np.argmax(np.hypot(*(p - p[0]).T)))
    return p[rec(0, k) + rec(k, len(p) - 1)]


def path(pts):
    """A closed Catmull-Rom spline through the points, as cubic Beziers."""
    n = len(pts)
    d = f"M{pts[0][0]:.1f},{pts[0][1]:.1f}"
    for i in range(n):
        p0, p1, p2, p3 = pts[i - 1], pts[i], pts[(i + 1) % n], pts[(i + 2) % n]
        c1, c2 = p1 + (p2 - p0) / 6, p2 - (p3 - p1) / 6
        d += f" C{c1[0]:.1f},{c1[1]:.1f} {c2[0]:.1f},{c2[1]:.1f} {p2[0]:.1f},{p2[1]:.1f}"
    return d + " Z"


if __name__ == "__main__":
    d = path(simplify(outline(PARAMS)))
    svg = (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" width="1024" height="1024">\n'
        '  <!-- Generated by app/design/logo.py; edit PARAMS there, not this file. -->\n'
        '  <defs><linearGradient id="nordyg" x1="0.15" y1="0.1" x2="0.85" y2="0.9">'
        f'<stop offset="0" stop-color="{GRADIENT[0]}"/><stop offset="1" stop-color="{GRADIENT[1]}"/>'
        '</linearGradient></defs>\n'
        f'  <path fill="url(#nordyg)" d="{d}"/>\n'
        '</svg>\n'
    )
    out = Path(__file__).with_name("logo.svg")
    out.write_text(svg)
    print(f"wrote {out}")
